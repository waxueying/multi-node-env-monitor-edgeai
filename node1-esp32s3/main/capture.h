#pragma once

/* ===========================================================================
 * 采集模式（数据采集固件）—— 给 AI 模型采集撞击波形训练数据
 *
 * 用途：把节点1 临时烧成"采集器"，把 MPU6050 的原始三轴加速度经串口导出，
 *       由 PC 存成日志，喂给 ai_training/train_impact.py 训练模型。
 *
 * 开关：把下面 CAPTURE_MODE 改成 1 重新编译 = 采集模式；
 *       改回 0 = 原来的正常运行固件。两种模式互斥，不会同时跑。
 *
 * 两种导出方式：
 *   自动 —— 动态分量越过 CAP_TRIGGER_G 就导出（1/2/3 类靠它，能采到"触发点"）；
 *   手动 —— 串口发 e 立刻导出当前缓冲（0 类 idle 靠它，静止数据没有触发点）。
 *
 * 采集模式刻意不初始化 CAN 与 DHT11：
 *   - DHT11 读取会关中断约 25ms，会打乱 100Hz 采样节奏；
 *   - CAN 收发与日志抢总线/串口，白白引入干扰。
 * 所以采集时节点只做"读 MPU6050 + 打日志"这一件事。
 * =========================================================================== */

#define CAPTURE_MODE        0       /* 1=采集模式，0=正常运行（原固件） */

#if CAPTURE_MODE

/* ---- 采集参数 ---- */
#define CAP_SAMPLE_MS       10      /* 采样周期（100Hz，与正常运行固件一致） */
#define CAP_WINDOW          100     /* 环形缓冲样本数：导出时一次性输出最近 100 个样本 */
#define CAP_SETTLE_N        100     /* 上电后多少个样本用于估计重力（这段时间内不触发） */

/* 触发阈值：动态分量（去掉重力后的加速度模长）超过它就算"有动作"。
 * 刻意取 0.15g —— 比正常运行固件的撞击阈值 0.50g 低，
 * 这样"轻拍"和"缓慢推压"也能被捕获，否则这两类根本采不到数据。 */
#define CAP_TRIGGER_G       0.15f

/* 触发后再等这么多个样本才导出。
 * 导出的是"最近 CAP_WINDOW 个样本"，所以触发点刚好落在正中间：
 *     [触发前 49 个] [触发点] [触发后 50 个]
 * 训练脚本从这个 100 样本里取中间 50 个当输入窗口（触发点居中），
 * 再用最前面 20 个静止样本估计重力方向 —— 三处参数是配套的，别单独改。 */
#define CAP_POST_SAMPLES    50

#define CAP_COOLDOWN_N      100     /* 导出后冷却多少个样本（1s），防止一个动作导出好几份 */

/* 上电默认类别，串口命令可随时覆盖。类别号与 train_impact.py 的约定一致：
 *   0 = idle 干扰（没人碰货架：走路、搬货等环境振动）
 *   1 = tap  瞬态轻击（高尖峰、快速衰减）
 *   2 = push 持续推压（幅值低、持续时间长）
 *   3 = hit  剧烈冲击（峰值极高、多次振荡） */
#define CAP_START_CLASS     0

#if (CAP_START_CLASS < 0) || (CAP_START_CLASS > 3)
#error "CAP_START_CLASS 只能是 0~3"
#endif

/* 运行采集模式：初始化 IMU，建立采样任务与串口命令任务。本函数不返回 */
void capture_mode_run(void);

#endif /* CAPTURE_MODE */
