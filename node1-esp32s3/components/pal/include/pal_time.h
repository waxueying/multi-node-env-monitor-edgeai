#pragma once

#include <stdint.h>

/* ============================================================================
 * 平台抽象层 PAL（Platform Abstraction Layer）—— 本工程的最底层
 *
 * 【为什么叫 pal 而不是 hal】
 *   ESP-IDF 自己有一个叫 hal 的组件（components/hal），如果我也建一个同名组件，
 *   会把 IDF 的覆盖掉 —— mbedtls 找不到 hal/sha_types.h，整个工程编译失败。
 *   所以这里用业界同样通用的名字 PAL（平台抽象层），职责与 HAL 完全一致。
 *
 * 【这层放什么】
 *   全工程只有这一处直接调用底层平台 API。换芯片 / 换 RTOS 时只改本文件，
 *   上层业务代码（协议时间戳、延时）一行都不用动。
 *
 * 【为什么只有时间、没有别的】
 *   ESP-IDF 本身已经提供了完整的驱动层（GPIO/I2C/TWAI/WiFi…），再包一层只是重复。
 *   这一层只放"真的会被换掉"的东西 —— 薄是对的，厚了说明业务逻辑漏下来了。
 * ========================================================================== */

/* 毫秒时间戳，单调递增（给 CAN 帧打时间戳用） */
uint32_t pal_time_ms(void);

/* 微秒时间戳，单调递增 */
int64_t pal_time_us(void);

